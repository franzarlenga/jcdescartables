-- Si otro producto ya usa el nuevo SKU, abortar antes de efectuar cambios.
do $$ begin
 if exists (
    select 1 from public.jc_products p
    join jc_sku_change_map m on p.sku=m.new_sku
    where not exists (select 1 from public.jc_products q where q.sku=m.old_sku and q.id=p.id)
 ) then raise exception 'Conflicto de SKU antes de migrar'; end if;
end $$;

insert into public.jc_sku_aliases(old_sku,product_id,new_sku)
select m.old_sku,p.id,m.new_sku
from jc_sku_change_map m join public.jc_products p on p.sku in (m.old_sku,m.new_sku)
on conflict(old_sku) do update set product_id=excluded.product_id,new_sku=excluded.new_sku;

update public.jc_products p set sku=m.new_sku
from jc_sku_change_map m where p.sku=m.old_sku;

